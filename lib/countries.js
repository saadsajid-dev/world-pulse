const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const CASE_SENSITIVE = new Set(['US', 'UK', 'USA', 'UAE', 'DRC', 'PNG', 'RSF', 'IDF', 'IRGC', 'FBI', 'CIA', 'DPRK', 'Male', 'Xi', 'Lao', 'Congress', 'America']);

function buildMatchers(table) {
  const list = [];
  for (const [country, words] of Object.entries(table)) {
    for (const w of words) {
      const flags = CASE_SENSITIVE.has(w) ? 'g' : 'gi';
      list.push({ country, len: w.length, re: new RegExp(`(?<![\\p{L}\\p{N}])${esc(w)}(?![\\p{L}\\p{N}])`, flags + 'u') });
    }
  }
  return list.sort((a, b) => b.len - a.len);   // longest first: "South Sudan" beats "Sudan"
}
const PLACE_M = buildMatchers(PLACES);
const PEOPLE_M = buildMatchers(PEOPLE);

function scan(text, matchers) {
  let t = text; const found = [];
  for (const m of matchers) {
    m.re.lastIndex = 0;
    t = t.replace(m.re, (s, i) => { found.push({ country: m.country, i }); return ' '.repeat(s.length); });   // mask so shorter names can't re-match
  }
  found.sort((a, b) => a.i - b.i);
  return [...new Set(found.map(f => f.country))];
}

/** Countries a headline is about, in the order they are mentioned. */
export function countriesIn(title, desc = '') {
  let c = scan(title, PLACE_M);
  if (!c.length) c = scan(title, PEOPLE_M);
  if (!c.length && desc) c = scan(desc.slice(0, 220), PLACE_M).slice(0, 1);   // fall back to the first sentence of the summary
  return c;
}
